package otlp

import (
	"strings"

	commonpb "go.opentelemetry.io/proto/otlp/common/v1"
)

// v0.10.2414 — mainframe (CICS via CTG) and IBM MQ (via JMS) recognition
// at ingest (docs/operator/mainframe-ctg-mq-tracing.md §4).
//
// Why here and not in SQL: every outbound read (topology_edges_5m infra
// pass, External dependencies, messaging_summary_5m / caller MVs) keys on
// the typed columns kind / peer_service / msg_system. Deriving them once
// in the converter makes all of those pick the calls up with no MV or
// materialised-column change and no raw-span aggregate. The attribute
// arrays stay verbatim — only the derived typed columns change.

const (
	mainframePeer   = "mainframe"
	cicsCTGSystem   = "cics_ctg"
	ibmMQSystem     = "ibmmq"
	ctgClassPrefix  = "com.ibm.ctg."
	jmsSystem       = "jms"
	jmsMessageIDKey = "messaging.message.id"
)

// isCTGCall reports whether a span is a call through the CICS Transaction
// Gateway Java client:
//   - the OTel Java agent's methods.include span on a com.ibm.ctg.* class
//     (code.namespace = "com.ibm.ctg.client.JavaGateway", or the newer
//     semconv code.function.name = "com.ibm.ctg.client.JavaGateway.flow");
//   - the manual span shape from the guide (rpc.system = "cics_ctg", or
//     cics.transaction_id / cics.program).
func isCTGCall(attrs []*commonpb.KeyValue, rpcSystem string) bool {
	if rpcSystem == cicsCTGSystem {
		return true
	}
	for _, kv := range attrs {
		switch kv.Key {
		case "code.namespace", "code.function.name":
			if strings.HasPrefix(anyValStr(kv.Value), ctgClassPrefix) {
				return true
			}
		case "cics.transaction_id", "cics.program":
			if anyValStr(kv.Value) != "" {
				return true
			}
		}
	}
	return false
}

// applyMainframe derives the outbound-call columns of a CTG span. Only
// internal and client spans qualify: a server/consumer span carrying
// cics.* attributes is the receiving side, not a call to the mainframe.
// The agent span is INTERNAL with no peer, so it becomes kind=client,
// peer_service=mainframe, rpc_system=cics_ctg — the same columns the
// manual CLIENT span from the guide carries. An explicit peer.service or
// rpc.system wins over the derived value.
func applyMainframe(attrs []*commonpb.KeyValue, kind, peer, rpcSystem string) (string, string, string) {
	if kind != "internal" && kind != "client" {
		return kind, peer, rpcSystem
	}
	if kind == "client" && peer != "" && rpcSystem != "" {
		return kind, peer, rpcSystem
	}
	if !isCTGCall(attrs, rpcSystem) {
		return kind, peer, rpcSystem
	}
	if peer == "" {
		peer = mainframePeer
	}
	if rpcSystem == "" {
		rpcSystem = cicsCTGSystem
	}
	return "client", peer, rpcSystem
}

// ibmMQMessageIDPrefixes — the 4-byte product identifier an IBM MQ queue
// manager puts at the start of every MsgId it generates (MQMD MsgId
// reference: "AMQ " on distributed platforms, "CSQ " on z/OS, in ASCII
// or EBCDIC). IBM MQ classes for JMS expose MsgId as JMSMessageID =
// "ID:" + 48 lowercase hex digits, and the OTel Java agent's JMS
// instrumentation copies JMSMessageID to messaging.message.id at span end
// (producer and consumer).
var ibmMQMessageIDPrefixes = [...]string{
	"414d5120", // "AMQ " ASCII
	"43535120", // "CSQ " ASCII
	"c1d4d840", // "AMQ " EBCDIC
	"c3e2d840", // "CSQ " EBCDIC
}

// ibmMQMessageID reports whether a JMS message id was generated by an IBM
// MQ queue manager: "ID:" + exactly 48 hex digits starting with a product
// identifier above. Application-supplied MsgIds that happen to start with
// those bytes are possible but IBM tells applications to avoid A–I
// leading characters, so the false-positive rate is negligible.
func ibmMQMessageID(id string) bool {
	const hexLen = 48
	if len(id) != 3+hexLen || !strings.HasPrefix(id, "ID:") {
		return false
	}
	hex := strings.ToLower(id[3:])
	for i := 0; i < hexLen; i++ {
		c := hex[i]
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	for _, p := range ibmMQMessageIDPrefixes {
		if strings.HasPrefix(hex, p) {
			return true
		}
	}
	return false
}

// applyIBMMQ maps messaging.system="jms" to "ibmmq" when the message id
// proves the provider is IBM MQ. The agent's JMS instrumentation always
// reports "jms" (the provider is not in the scope, client id, destination
// or resource), so the message id is the only reliable evidence. A send
// that failed before the provider assigned an id stays "jms".
func applyIBMMQ(attrs []*commonpb.KeyValue, msgSystem string) string {
	if msgSystem != jmsSystem {
		return msgSystem
	}
	if ibmMQMessageID(attrStr(attrs, jmsMessageIDKey, "")) {
		return ibmMQSystem
	}
	return msgSystem
}
